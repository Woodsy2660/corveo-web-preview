#!/usr/bin/env zsh
# Generates ios/Secrets.xcconfig (gitignored) from ../.env.local.
# Only VITE_SUPABASE_URL, VITE_SUPABASE_PUBLISHABLE_KEY and VITE_APP_ENV are read.
# xcconfig treats "//" as a comment, so the URL is written with the $() trick.
set -e
ROOT="${0:A:h}"
ENVF="$ROOT/../.env.local"
[[ -f "$ENVF" ]] || { echo "no .env.local at $ENVF"; exit 1; }
url=$(grep -E '^VITE_SUPABASE_URL=' "$ENVF" | cut -d= -f2- | tr -d '\r')
key=$(grep -E '^VITE_SUPABASE_PUBLISHABLE_KEY=' "$ENVF" | cut -d= -f2- | tr -d '\r')
env=$(grep -E '^VITE_APP_ENV=' "$ENVF" | cut -d= -f2- | tr -d '\r')
url_x=${url/:\/\//:\/\$()\/}
cat > "$ROOT/Secrets.xcconfig" <<EOT
// GENERATED by gen-secrets.sh from ../.env.local. Do not commit. Non-production only.
SUPABASE_URL = $url_x
SUPABASE_PUBLISHABLE_KEY = $key
APP_ENV = ${env:-local}
EOT
echo "wrote $ROOT/Secrets.xcconfig (env=${env:-local}, host=$(echo $url | sed -E 's#https?://##'))"
